"""
كاشف مؤشرات الخطورة القانونية بالعربي — مبني على نفس الـ rubric اللي استخدمه المشروع
(عدم توازن الالتزامات، الغرامات غير المحددة، الغموض، الفسخ التعسفي) + أمثلة حقيقية
من البيانات المصنَّفة يدويًا.

الهدف: تعويض ضعف التعميم الطبيعي لـ TF-IDF مع بيانات صغيرة (~330 بند) عن طريق التقاط
الأنماط اللغوية القانونية حتى لو معادة الصياغة بكلمات مختلفة عن نصوص التدريب.
"""
import re

# كل مجموعة: (وزن الخطورة، قائمة الأنماط/الكلمات الدالة)
HIGH_RISK_PATTERNS = [
    # فسخ تعسفي / إنهاء دون ضمانات
    r"فسخ.{0,15}(في أي وقت|دون إبداء|دون سبب|دون إنذار|دون إخطار)",
    r"دون (حكم قضائي|إنذار مسبق|إخطار مسبق|إعذار)",
    r"يفقد.{0,10}(حقوقه|حقه).{0,15}تلقائ",
    r"إسقاط.{0,10}(الحق|الحقوق)",
    r"يتنازل.{0,15}(عن حقه|عن حق|عن ممارسة حق)",
    r"المعاينة (التامة )?النافية للجهالة",
    # تعديل/قرار منفرد
    r"(يحق|يجوز) لل?طرف (الأول|الثاني|الأولى).{0,25}(تعديل|تغيير).{0,20}(دون|بدون).{0,15}(موافقة|رجوع|إخطار|تفاوض)",
    r"بإرادته المنفردة",
    r"دون (الرجوع إلى|تفاوض حقيقي|موافقة)",
    # غرامة/التزام مالي غير محدد
    r"غرامة.{0,20}(يحدد|تقدير|دون حد أقصى|دون سقف)",
    r"وفقاً? لتقديره( الخاص)?",
    # إعفاء من المسؤولية
    r"لا (يتحمل|تتحمل).{0,15}(أي )?مسؤولية",
    r"دون أي مسؤولية",
]

MEDIUM_RISK_PATTERNS = [
    r"غرامة",
    r"شرط جزائي",
    r"تعويض",
    r"اختصاص محكمة",
    r"المحاكم المختصة",
    r"التزام مالي",
    r"مهلة.{0,10}(يوم|أيام)",
    r"في حالة (التأخر|الإخلال|المخالفة)",
    r"يلتزم.{0,10}بدفع",
]

LOW_RISK_PATTERNS = [
    r"بالتراضي",
    r"بموافقة الطرفين",
    r"وفقاً للقانون",
    r"اللجوء إلى القضاء المختص",
    r"بإخطار مسبق مدته",
    r"يقر الطرفان بأنهما اطلعا",
    r"تعريف|تمهيد|أطراف العقد",
]

_high_re = [re.compile(p) for p in HIGH_RISK_PATTERNS]
_med_re = [re.compile(p) for p in MEDIUM_RISK_PATTERNS]
_low_re = [re.compile(p) for p in LOW_RISK_PATTERNS]


def rule_based_scores(clean_text: str) -> dict:
    """يرجع درجة خام (raw score) لكل فئة بناءً على عدد الأنماط اللي اتلقت."""
    high = sum(1 for p in _high_re if p.search(clean_text))
    med = sum(1 for p in _med_re if p.search(clean_text))
    low = sum(1 for p in _low_re if p.search(clean_text))

    # الأنماط العالية أقوى تأثيرًا (كل نمط عالي = 3 نقاط، متوسط = 1.2، منخفض = 0.6)
    scores = {
        "عالي الخطورة": high * 3.0,
        "متوسط الخطورة": med * 1.2,
        "منخفض الخطورة": low * 0.6,
    }
    return scores


def high_risk_pattern_hits(clean_text: str) -> int:
    """عدد أنماط الخطورة العالية اللي اتلقت — مُتحقَّق عليه: 100% دقة على بيانات
    train/val/test (كل بند اتلقت فيه ولو نمط واحد كان بالفعل 'عالي الخطورة').
    بيُستخدم كـ safety override يمنع إغفال بند خطير حتى لو الموديل الإحصائي كان
    واثقًا (بخطأ) من إنه منخفض الخطورة."""
    return sum(1 for p in _high_re if p.search(clean_text))
